def course_activity(topic: str, reply_language: str) -> dict | None:
    course = COURSES.get(topic)
    if course is None:
        return None

    language = 1 if reply_language == "en" else 0
    title, cases = course
    return {
        "topic": topic,
        "title": title[language],
        "instruction": INSTRUCTION[language],
        "cases": [
            {
                "label": case.label[language],
                "context": case.context[language],
                "question": case.question[language],
                "choices": [choice[language] for choice in case.choices],
                "answer_index": case.answer,
                "feedback": case.feedback[language],
            }
            for case in cases
        ],
    }
